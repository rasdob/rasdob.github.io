/** Fixed-length planar schematic: shoulder, elbow and wrist. */
export function armGeometry(x){
 const shoulder=[115,300],wrist=[258+x,161],length=160;
 const dx=wrist[0]-shoulder[0],dy=wrist[1]-shoulder[1],distance=Math.hypot(dx,dy);
 if(distance>2*length||distance===0)throw new RangeError('Wrist outside schematic reach');
 const angle=Math.atan2(dy,dx)-Math.acos(distance/(2*length));
 return [shoulder,[shoulder[0]+length*Math.cos(angle),shoulder[1]+length*Math.sin(angle)],wrist];
}
export function responsePosition(t,tau=.48,g=.78){
 if(!(tau>0)||!Number.isFinite(g))throw new RangeError('Invalid response parameters');
 return g*((t>1?(t-1)-tau*(1-Math.exp(-(t-1)/tau)):0)-(t>3?(t-3)-tau*(1-Math.exp(-(t-3)/tau)):0));
}
/** Synthetic position feedback for the teaching scene, never experimental data. */
export function responseHistory({tau=.48,g=.78,noise=.0008}={}){
 const h=.25;
 return Array.from({length:21},(_,i)=>{
  const time=i*h,mid=time-h/2;
  return {time,q:responsePosition(time,tau,g)+noise*Math.sin(time*8),command:mid>=1&&mid<3?1:0};
 });
}
/** Same interval recurrence as the paper: search tau, fit g, then score residuals. */
export function fitResponseCandidates(history,timeConstants=[.12,.50,1.05]){
 if(history.length<3)throw new RangeError('Position history is too short');
 const h=history[1].time-history[0].time,last=history.at(-1).time;
 if(!(h>0)||history.some((r,i)=>!Number.isFinite(r.q)||!Number.isFinite(r.command)||!Number.isFinite(r.time)||(i>0&&Math.abs(r.time-history[i-1].time-h)>1e-9)))throw new RangeError('Expected finite, equally spaced position feedback');
 if(!timeConstants.length||timeConstants.some(tau=>!(tau>0)||!Number.isFinite(tau)))throw new RangeError('Invalid response grid');
 return timeConstants.map(tau=>{
  const a=Math.exp(-h/tau),b=tau*(1-a)/h;
  const rows=history.slice(2).map((r,index)=>{
   const k=index+2,previous=(history[k-1].q-history[k-2].q)/h;
   const actual=(r.q-history[k-1].q)/h;
   return {time:r.time,actual,previous,x:(1-b)*r.command+(b-a)*history[k-1].command,y:actual-a*previous,weight:Math.exp((r.time-last)/1.5)};
  });
  const numerator=rows.reduce((sum,r)=>sum+r.weight*r.x*r.y,0),denominator=rows.reduce((sum,r)=>sum+r.weight*r.x*r.x,0);
  const gain=clamp(numerator/Math.max(denominator,1e-12),.5,1.4);
  const cost=rows.reduce((sum,r)=>sum+r.weight*(r.y-gain*r.x)**2,0);
  const points=rows.map(r=>({time:r.time,actual:h*r.actual,predicted:h*(a*r.previous+gain*r.x)}));
  return {tau,gain,cost,points};
 });
}
