/** Exact unit rectangular command response: x-dot = (g*u-x)/tau. */
export function responseSample(t,tau=.48,g=.78){
  if(!(tau>0)||!Number.isFinite(g))throw new RangeError('Invalid response parameters');
  const on=1,off=3;
  const rise=t<=on?0:1-Math.exp(-(t-on)/tau);
  const decay=t<=off?0:1-Math.exp(-(t-off)/tau);
  return g*(rise-decay);
}
